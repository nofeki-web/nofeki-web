begin;

create schema if not exists private;

create table private.pqr_outbox (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.pqr_submissions(id) on delete restrict,
  event_key text not null unique,
  event_type text not null check (
    event_type in ('applicant_confirmation', 'internal_alert', 'admin_response')
  ),
  status text not null default 'pending' check (
    status in ('pending', 'processing', 'delivered', 'dead')
  ),
  attempts integer not null default 0 check (attempts >= 0),
  max_attempts integer not null default 8 check (max_attempts between 1 and 25),
  available_at timestamptz not null default now(),
  locked_until timestamptz,
  lock_token uuid,
  provider_message_id text,
  last_error_code text,
  last_error_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pqr_outbox_processing_lease_check check (
    (status = 'processing' and lock_token is not null and locked_until is not null)
    or
    (status <> 'processing' and lock_token is null and locked_until is null)
  )
);

create index pqr_outbox_ready_idx
  on private.pqr_outbox (available_at, created_at)
  where status = 'pending';

create index pqr_outbox_expired_lease_idx
  on private.pqr_outbox (locked_until)
  where status = 'processing';

-- A stable key is generated by the browser once per form attempt and reused
-- on network retry. The fingerprint is a server-computed SHA-256 digest of a
-- canonicalized validated payload; never trust a client-supplied fingerprint.
create table private.pqr_request_keys (
  request_key uuid primary key,
  request_fingerprint text not null check (request_fingerprint ~ '^[0-9a-f]{64}$'),
  submission_id uuid not null references public.pqr_submissions(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index pqr_request_keys_submission_idx
  on private.pqr_request_keys (submission_id);

alter table private.pqr_outbox enable row level security;
alter table private.pqr_request_keys enable row level security;

revoke all on schema private from public, anon, authenticated;
grant usage on schema private to service_role;
revoke all on private.pqr_outbox, private.pqr_request_keys from public, anon, authenticated;
grant select, insert, update on private.pqr_outbox, private.pqr_request_keys to service_role;

-- Claim a bounded batch. Expired leases are reclaimable; a fresh token fences
-- off stale workers. The transaction commits before the worker calls Resend.
create or replace function public.pqr_outbox_claim(
  p_batch_size integer default 10,
  p_lease_seconds integer default 90
)
returns table (
  outbox_id uuid,
  submission_id uuid,
  event_key text,
  event_type text,
  lease_token uuid,
  attempt_number integer,
  lease_expires_at timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if p_batch_size < 1 or p_batch_size > 25 then
    raise exception 'invalid_batch_size' using errcode = '22023';
  end if;
  if p_lease_seconds < 15 or p_lease_seconds > 600 then
    raise exception 'invalid_lease_seconds' using errcode = '22023';
  end if;

  return query
  with candidates as (
    select o.id
    from private.pqr_outbox as o
    where
      (o.status = 'pending' and o.available_at <= pg_catalog.now())
      or
      (o.status = 'processing' and o.locked_until <= pg_catalog.now())
    order by o.available_at, o.created_at
    for update skip locked
    limit p_batch_size
  ),
  claimed as (
    update private.pqr_outbox as o
    set status = 'processing',
        attempts = o.attempts + 1,
        lock_token = gen_random_uuid(),
        locked_until = pg_catalog.now() + pg_catalog.make_interval(secs => p_lease_seconds),
        updated_at = pg_catalog.now()
    from candidates as c
    where o.id = c.id
    returning o.id, o.submission_id, o.event_key, o.event_type,
              o.lock_token, o.attempts, o.locked_until
  )
  select c.id, c.submission_id, c.event_key, c.event_type,
         c.lock_token, c.attempts, c.locked_until
  from claimed as c;
end;
$$;

-- Fenced success acknowledgement. A stale worker updates zero rows.
create or replace function public.pqr_outbox_finish(
  p_outbox_id uuid,
  p_lease_token uuid,
  p_provider_message_id text
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_rows integer;
begin
  update private.pqr_outbox
  set status = 'delivered',
      provider_message_id = nullif(pg_catalog.left(p_provider_message_id, 200), ''),
      delivered_at = pg_catalog.now(),
      lock_token = null,
      locked_until = null,
      last_error_code = null,
      updated_at = pg_catalog.now()
  where id = p_outbox_id
    and status = 'processing'
    and lock_token = p_lease_token;

  get diagnostics v_rows = row_count;
  return v_rows = 1;
end;
$$;

-- Retry with bounded exponential backoff calculated by the worker and passed
-- as seconds; only the current lease holder may schedule it.
create or replace function public.pqr_outbox_retry(
  p_outbox_id uuid,
  p_lease_token uuid,
  p_error_code text,
  p_delay_seconds integer
)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_row private.pqr_outbox%rowtype;
begin
  if p_delay_seconds < 1 or p_delay_seconds > 86400 then
    raise exception 'invalid_retry_delay' using errcode = '22023';
  end if;

  update private.pqr_outbox
  set status = case when attempts >= max_attempts then 'dead' else 'pending' end,
      available_at = pg_catalog.now() + pg_catalog.make_interval(secs => p_delay_seconds),
      lock_token = null,
      locked_until = null,
      last_error_code = pg_catalog.left(coalesce(p_error_code, 'provider_error'), 80),
      last_error_at = pg_catalog.now(),
      updated_at = pg_catalog.now()
  where id = p_outbox_id
    and status = 'processing'
    and lock_token = p_lease_token
  returning * into v_row;

  if not found then
    return 'stale_lease';
  end if;
  return v_row.status;
end;
$$;

-- The admin retry path must explicitly audit the operator in pqr_events and
-- requeue only a selected dead row. This function is intentionally omitted
-- until the deployed admin authorization contract is reconciled.

revoke all on function public.pqr_outbox_claim(integer, integer) from public, anon, authenticated;
revoke all on function public.pqr_outbox_finish(uuid, uuid, text) from public, anon, authenticated;
revoke all on function public.pqr_outbox_retry(uuid, uuid, text, integer) from public, anon, authenticated;
grant execute on function public.pqr_outbox_claim(integer, integer) to service_role;
grant execute on function public.pqr_outbox_finish(uuid, uuid, text) to service_role;
grant execute on function public.pqr_outbox_retry(uuid, uuid, text, integer) to service_role;

commit;

